LOCALES = [d.name for d in MESSAGES_DIR.iterdir() if d.is_dir()]

def update_locale(loc: str):
    file_path = MESSAGES_DIR / loc / "uiC.json"
    if not file_path.exists():
        print(f"Skipping {loc}, {file_path} does not exist")
        return

    with open(file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if "auth" not in data:
        data["auth"] = {}
    if "gamepad" not in data:
        data["gamepad"] = {}

    auth_dict = AUTH_EN
    gamepad_dict = GAMEPAD_WIZARD_EN

    if loc == "fa":
        auth_dict = AUTH_FA
        gamepad_dict = GAMEPAD_WIZARD_FA
    elif loc == "nl":
        auth_dict = AUTH_NL
        gamepad_dict = GAMEPAD_WIZARD_NL
    elif loc == "ar":
        auth_dict = AUTH_AR
        gamepad_dict = GAMEPAD_WIZARD_EN
    elif loc == "en":
        auth_dict = AUTH_EN
        gamepad_dict = GAMEPAD_WIZARD_EN

    # Crucial: Populate both auth.modal.* (used by AuthModal.tsx) and auth.* (backwards compatibility)
    if "modal" not in data["auth"] or not isinstance(data["auth"]["modal"], dict):
        data["auth"]["modal"] = {}
    data["auth"]["modal"].update(auth_dict)
    data["auth"].update(auth_dict)
    data["gamepad"]["wizard"] = gamepad_dict

    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Updated {loc}/uiC.json successfully.")

for loc in LOCALES:
    update_locale(loc)
